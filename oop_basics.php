<?php

/**
 * Основы ООП в PHP: классы и объекты
 *
 * Этот файл содержит примеры из урока по объектно-ориентированному программированию.
 * Демонстрируется создание класса, создание объектов с помощью new
 * и вывод информации о них через var_dump().
 */

// --- Пример 1: Создание класса ---
class Cat
{
    // тело класса
}

// --- Пример 2: Создание одного объекта ---
$cat1 = new Cat();

echo "=== Один объект ===" . PHP_EOL;
var_dump($cat1);
echo PHP_EOL;

// --- Пример 3: Создание нескольких объектов ---
$cat2 = new Cat();
$cat3 = new Cat();

echo "=== Несколько объектов одного класса ===" . PHP_EOL;
var_dump($cat1);
var_dump($cat2);
var_dump($cat3);
echo PHP_EOL;

// --- Вывод ---
echo "Каждый объект имеет свой уникальный идентификатор (#1, #2, #3)," . PHP_EOL;
echo "но все они являются экземплярами одного и того же класса Cat." . PHP_EOL;
